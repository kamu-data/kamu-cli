/// Runs a [`SimpleResourceReconciler`] and records its outcomes through the
/// lifecycle primitives, within the transaction of its caller. The adapter
/// generated by `declare_simple_resource_controller_adapter!` owns those
/// transactions.
pub struct SimpleResourceControllerAdapterHelper<'a, R>
where
    R: EventSourcedResource,
{
    resource_aggregate_loader: &'a dyn ResourceAggregateLoader<R>,
    lifecycle_primitives: &'a dyn ResourceLifecyclePrimitives<R>,
    reconciler: &'a dyn SimpleResourceReconciler<R>,
}

impl<'a, R> SimpleResourceControllerAdapterHelper<'a, R>
where
    R: EventSourcedResource,
{
    pub fn new(
        resource_aggregate_loader: &'a dyn ResourceAggregateLoader<R>,
        lifecycle_primitives: &'a dyn ResourceLifecyclePrimitives<R>,
        reconciler: &'a dyn SimpleResourceReconciler<R>,
    ) -> Self {
        Self {
            resource_aggregate_loader,
            lifecycle_primitives,
            reconciler,
        }
    }

    pub async fn start_reconciliation_phase(
        &self,
        id: ResourceID,
    ) -> Result<Option<R>, SimpleResourceReconciliationError<R>> {
        // Phase 1 commits the "started" transition before the actual reconciliation
        // work, giving the second phase a stable persisted hand-off point.
        let started = self
            .lifecycle_primitives
            .begin_reconciliation(&id, None)
            .await?;

        Ok(started)
    }

    /// Records the outcome of reconciling `started`, the resource as phase 1
    /// left it. The outcome is written to the current state of the resource,
    /// provided its deletion was not requested, its generation is still the
    /// reconciled one and no other writer updated the status since phase 1.
    pub async fn finish_reconciliation_phase(
        &self,
        started: R,
    ) -> Result<(), SimpleResourceReconciliationError<R>> {
        let id = *started.id();
        let expected = ResourceExpectedVersion {
            generation: started.headers().generation,
            status_generation: started.headers().status_generation,
        };

        // Phase 2 runs in a separate transaction after the started state was
        // committed, so the resource may have changed in between.
        let recorded = match self.reconciler.reconcile(&started).await {
            Ok(()) => {
                self.lifecycle_primitives
                    .complete_reconciliation(&id, expected)
                    .await
            }
            Err(err) => {
                self.lifecycle_primitives
                    .fail_reconciliation(&id, expected, &err)
                    .await
            }
        };

        use ResourceLifecycleTransitionError as E;
        use ResourceStaleExpectationError as Stale;

        match recorded {
            Ok(_) => Ok(()),
            Err(E::Stale(Stale::DeletionRequested(_))) => {
                tracing::info!(
                    resource_id = %id,
                    "Discarding reconciliation outcome of a resource being deleted"
                );
                Ok(())
            }
            Err(E::Stale(Stale::GenerationChanged(conflict))) => {
                tracing::info!(
                    resource_id = %id,
                    reconciled_generation = conflict.expected,
                    current_generation = conflict.actual,
                    "Discarding reconciliation outcome of a superseded generation"
                );
                Ok(())
            }
            Err(
                err @ (E::Stale(Stale::StatusGenerationChanged(_))
                | E::LoadFailed(_)
                | E::ConcurrentModification(_)
                | E::Lifecycle(_)
                | E::Internal(_)),
            ) => Err(err.into()),
        }
    }

    /// Runs the cleanup of one resource. A failed cleanup is returned as an
    /// error, so that the transaction of the caller rolls back. Returns `None`
    /// when the resource does not wait for a cleanup.
    pub async fn cleanup(
        &self,
        id: ResourceID,
    ) -> Result<Option<ResourceCleanupAttempt>, ResourceCleanupTransactionError<R>> {
        let resource = self
            .resource_aggregate_loader
            .load(&id)
            .await
            .map_err(ResourceLoadError)
            .map_err(SimpleResourceDeletionError::LoadFailed)
            .map_err(ResourceCleanupTransactionError::Deletion)?;
        if !resource.needs_cleanup() {
            return Ok(None);
        }

        let status_generation = resource.headers().status_generation;
        match self.reconciler.cleanup(&resource).await {
            Ok(()) => Ok(Some(ResourceCleanupAttempt {
                id,
                status_generation,
                failure: None,
            })),
            Err(err) => {
                tracing::warn!(
                    resource_id = %id,
                    error = %err,
                    "Cleanup of a resource being deleted failed"
                );
                Err(ResourceCleanupTransactionError::CleanupFailed(
                    ResourceCleanupAttempt {
                        id,
                        status_generation,
                        failure: Some(Arc::new(err)),
                    },
                ))
            }
        }
    }

    /// Runs within one transaction: the outcomes and the `Deleted` message of
    /// the completed deletions commit together. A resource whose deletion
    /// completed meanwhile is skipped, and so is a failed cleanup of a resource
    /// whose status another writer updated since. When the same resource was
    /// cleaned up more than once, its last attempt counts.
    pub async fn record_outcomes(
        &self,
        attempts: &[ResourceCleanupAttempt],
    ) -> Result<(), SimpleResourceDeletionError<R>> {
        let mut completions = Vec::new();
        let mut failures = Vec::new();
        for attempt in last_attempt_per_resource(attempts) {
            match &attempt.failure {
                None => completions.push(ResourceDeletionCompletion {
                    id: attempt.id,
                    expected_status_generation: None,
                }),
                Some(error) => failures.push(ResourceCleanupFailure {
                    id: attempt.id,
                    expected_status_generation: attempt.status_generation,
                    error: Arc::clone(error),
                }),
            }
        }

        // Failures first, so the `Deleted` message is the last write
        let failed = self
            .lifecycle_primitives
            .record_cleanup_failure(&failures)
            .await?;
        let completed = self
            .lifecycle_primitives
            .complete_deletion(&completions)
            .await?;

        for skip in failed.skipped.iter().chain(&completed.skipped) {
            log_skipped_outcome(skip);
        }

        Ok(())
    }
}

/// The batch primitives take each resource at most once
fn last_attempt_per_resource(
    attempts: &[ResourceCleanupAttempt],
) -> impl Iterator<Item = &ResourceCleanupAttempt> {
    let last_index_by_id = attempts
        .iter()
        .enumerate()
        .map(|(index, attempt)| (attempt.id, index))
        .collect::<HashMap<_, _>>();

    attempts
        .iter()
        .enumerate()
        .filter(move |(index, attempt)| last_index_by_id[&attempt.id] == *index)
        .map(|(_, attempt)| attempt)
}

fn log_skipped_outcome(skip: &ResourceTransitionSkip) {
    match skip.reason {
        ResourceTransitionSkipReason::NotAwaitingCleanup => {}
        ResourceTransitionSkipReason::StatusConflict(conflict) => {
            tracing::info!(
                resource_id = %skip.id,
                error = %conflict,
                "Skipping cleanup outcome: status was updated concurrently"
            );
        }
    }
}

